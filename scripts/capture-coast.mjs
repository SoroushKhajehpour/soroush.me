import { chromium } from '@playwright/test';
import { mkdir, copyFile, writeFile } from 'node:fs/promises';
const base=process.env.COAST_URL || 'http://localhost:3001';
const out='docs/verification';
await mkdir(`${out}/phases`,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1585,height:992},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('requestfailed',r=>errors.push(`${r.failure()?.errorText}: ${r.url()}`));
await page.goto(`${base}/?scene=reference`,{waitUntil:'networkidle'});
await page.waitForFunction(()=>window.__coast?.ready);
await page.mouse.move(-5,-5);
await page.screenshot({path:`${out}/canonical.png`});
for(const time of [0,1,3,5,8,13,30,60,180,600]) {
  await page.evaluate(t=>window.__coast.set({time:t,paused:true}),time);
  await page.screenshot({path:`${out}/phases/${time}.png`});
}
await page.evaluate(()=>window.__coast.set({time:3,paused:true}));
await page.screenshot({path:`${out}/phase-3.png`});
await page.evaluate(()=>window.__coast.reference());
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:`${out}/mobile.png`,fullPage:true});
await page.setViewportSize({width:1920,height:1080});
await page.screenshot({path:`${out}/wide.png`});
await page.setViewportSize({width:1585,height:992});
await page.emulateMedia({reducedMotion:'reduce'});
await page.screenshot({path:`${out}/reduced-motion.png`});
await page.close();
const videoContext=await browser.newContext({viewport:{width:1585,height:992},deviceScaleFactor:1,recordVideo:{dir:`${out}/raw-video`,size:{width:1585,height:992}}});
const motion=await videoContext.newPage();
await motion.goto(base,{waitUntil:'networkidle'});await motion.waitForFunction(()=>window.__coast?.ready);await motion.mouse.move(-5,-5);
await motion.waitForTimeout(10000);
const performance=await motion.evaluate(()=>window.__coast.get());
const video=motion.video();
await videoContext.close();
await copyFile(await video.path(),`${out}/waves.webm`);
await writeFile(`${out}/browser.json`,JSON.stringify({browser:await browser.version(),errors,performance},null,2)+'\n');
await browser.close();
console.log(JSON.stringify({errors,performance}));
if(errors.length) process.exitCode=1;
